"""RAF-DB Dataset and DataLoader Module.

Implements both raw Parquet and high-performance preprocessed cached datasets:
1. CachedRAFDBDataset:
   - High-throughput offline cached dataset loading from data/cache/rafdb_cache/{train,val,test}/.
   - Bypasses MediaPipe runtime, raw Parquet decoding, face detection, and geometric alignment.
   - Converts uint8 RGB (224, 224, 3) to ImageNet-normalized float32 (3, 224, 224) tensors.
   - Exposes pre-extracted 62-D facial geometry vectors and validity flags.
2. RAFDBDataset:
   - Raw Parquet-based online extraction dataset adhering to Step 1 & 2 contract.
   - Preserved for parity verification and online extraction fallback.
"""

import csv
import json
import logging
import os
from typing import Any, Dict, List, Optional, Tuple, Union

import cv2
import numpy as np
import pyarrow.parquet as pq

try:
    import torch
    from torch.utils.data import Dataset, DataLoader
    _TORCH_AVAILABLE = True
except ImportError:
    _TORCH_AVAILABLE = False
    torch = None
    Dataset = object  # type: ignore
    DataLoader = None  # type: ignore

from src.preprocessing.face_pipeline import FacePipeline

logger = logging.getLogger(__name__)

# Canonical Emotion Label Mapping (RAF-DB 1-indexed -> Canonical 0-indexed)
CANONICAL_CLASS_NAMES: List[str] = [
    "Neutral",   # 0
    "Happy",     # 1
    "Sad",       # 2
    "Surprise",  # 3
    "Fear",      # 4
    "Disgust",   # 5
    "Angry",     # 6
]

# Standard ImageNet normalization constants (matching FacePipeline)
IMAGENET_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
IMAGENET_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)

# In-memory cached lookup for Parquet image bytes: path -> bytes
_PARQUET_STORE_CACHE: Dict[str, Dict[str, bytes]] = {}


def get_parquet_image_store(parquet_path: str) -> Dict[str, bytes]:
    """
    Loads and caches all raw image bytes from the RAF-DB Parquet file.
    The Parquet file is ~34MB, making an in-memory dictionary lookup (~35MB)
    extremely fast (sub-millisecond O(1) random access per item).
    """
    abs_parquet = os.path.abspath(parquet_path)
    if abs_parquet not in _PARQUET_STORE_CACHE:
        if not os.path.exists(abs_parquet):
            raise FileNotFoundError(f"Parquet source not found at {abs_parquet}")
        table = pq.read_table(abs_parquet)
        store: Dict[str, bytes] = {}
        img_col = table["image"]
        num_rows = len(table)
        for i in range(num_rows):
            item = img_col[i].as_py()
            store[item["path"]] = item["bytes"]
        _PARQUET_STORE_CACHE[abs_parquet] = store
        logger.info(f"Loaded and indexed {len(store)} images from {abs_parquet}")
    return _PARQUET_STORE_CACHE[abs_parquet]


class CachedRAFDBDataset(Dataset):
    """
    High-performance PyTorch Dataset for preprocessed RAF-DB facial emotion recognition.

    Loads pre-extracted (224, 224, 3) uint8 RGB crops and 62-D geometry vectors from
    offline cache generated by scripts/build_rafdb_cache.py:
    - Bypasses MediaPipe runtime, raw Parquet decoding, face detection, and roll-based alignment.
    - Eliminates CPU bottleneck during training iterations.
    - Applies on-the-fly ImageNet mean/std normalization and HWC -> CHW transposition.
    - Returns dictionaries fully compatible with BaselineTrainer and spatial baseline models.
    """

    def __init__(
        self,
        split: str = "train",
        cache_dir: str = "data/cache/rafdb_cache",
        transform: Optional[Any] = None,
    ):
        """
        Args:
            split: Dataset split ('train', 'val', or 'test').
            cache_dir: Root directory of the precomputed cache.
            transform: Optional additional transform applied to the image tensor.
        """
        super().__init__()
        valid_splits = ("train", "val", "test")
        if split not in valid_splits:
            raise ValueError(f"Invalid split '{split}'. Expected one of {valid_splits}.")

        self.split = split
        self.cache_dir = cache_dir
        self.split_dir = os.path.join(cache_dir, split)
        self.transform = transform

        if not os.path.isdir(self.split_dir):
            raise FileNotFoundError(
                f"Cached split directory not found at: {self.split_dir}.\n"
                f"Please ensure cache is generated at {cache_dir} via scripts/build_rafdb_cache.py."
            )

        # 1. Attempt loading split index.json for fast O(1) metadata lookups
        index_path = os.path.join(self.split_dir, "index.json")
        self.samples: List[Dict[str, Any]] = []

        if os.path.isfile(index_path):
            with open(index_path, "r", encoding="utf-8") as f:
                raw_index = json.load(f)
            for idx, item in enumerate(raw_index):
                filename = item.get("filename")
                if not filename:
                    continue
                file_path = os.path.join(self.split_dir, filename)
                raw_label = item.get("label", 0)
                label_int = int(raw_label) if raw_label is not None else 0
                self.samples.append({
                    "file_path": file_path,
                    "filename": filename,
                    "source_path": item.get("source_path", filename),
                    "label": label_int,
                    "class_name": item.get("class_name", CANONICAL_CLASS_NAMES[label_int]),
                    "geometry_valid": bool(item.get("geometry_valid", False)),
                    "fallback_used": bool(item.get("fallback_used", False)),
                    "sample_id": item.get("sample_id", idx),
                })
        else:
            # Fallback: scan directory for .npz files deterministically
            npz_files = sorted([f for f in os.listdir(self.split_dir) if f.endswith(".npz")])
            for idx, fname in enumerate(npz_files):
                file_path = os.path.join(self.split_dir, fname)
                self.samples.append({
                    "file_path": file_path,
                    "filename": fname,
                    "source_path": fname,
                    "label": None,
                    "class_name": None,
                    "geometry_valid": None,
                    "fallback_used": None,
                    "sample_id": idx,
                })

        logger.info(f"Loaded CachedRAFDBDataset ({split}): {len(self.samples)} samples from {self.split_dir}")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """
        Loads preprocessed sample from disk .npz archive, normalizes image tensor,
        and returns dictionary matching the training contract.

        Returns:
            Dict containing:
                "image": Tensor of shape (3, 224, 224), float32, ImageNet-normalized
                "label": int in range 0..6 (canonical class index)
                "geometry": Tensor of shape (62,), float32
                "geometry_valid": bool
                "face_detected": bool
                "fallback_used": bool
                "image_path": str
                "source_path": str
                "split": str
                "class_name": str
                "sample_id": int
        """
        entry = self.samples[idx]
        file_path = entry["file_path"]

        data = np.load(file_path)

        # 1. Image preprocessing: uint8 (224, 224, 3) -> float32 (3, 224, 224) ImageNet-normalized
        img_uint8 = data["image"]  # shape (224, 224, 3), dtype uint8, RGB
        img_float = (img_uint8.astype(np.float32) / 255.0 - IMAGENET_MEAN) / IMAGENET_STD
        img_chw = np.transpose(img_float, (2, 0, 1)).astype(np.float32)

        # 2. Geometry vector: float32 (62,)
        geom_np = data["geometry"].astype(np.float32)
        geom_valid = bool(data["geometry_valid"])

        # 3. Label and metadata
        label = int(data["label"])
        source_path = str(data["source_path"]) if "source_path" in data else entry.get("source_path", "")
        split_name = str(data["split"]) if "split" in data else self.split
        class_name = entry.get("class_name") or CANONICAL_CLASS_NAMES[label]
        fallback_used = bool(data["fallback_used"]) if "fallback_used" in data else (
            entry.get("fallback_used") if entry.get("fallback_used") is not None else not geom_valid
        )
        face_detected = not fallback_used

        # Convert to PyTorch tensors if torch is available
        if _TORCH_AVAILABLE and torch is not None:
            image_tensor = torch.from_numpy(img_chw).float()
            if self.transform is not None:
                image_tensor = self.transform(image_tensor)
            geometry_tensor = torch.from_numpy(geom_np).float()
        else:
            image_tensor = img_chw
            geometry_tensor = geom_np

        return {
            "image": image_tensor,
            "label": label,
            "geometry": geometry_tensor,
            "geometry_valid": geom_valid,
            "face_detected": face_detected,
            "fallback_used": fallback_used,
            "image_path": source_path,
            "source_path": source_path,
            "split": split_name,
            "class_name": class_name,
            "sample_id": entry.get("sample_id", idx),
        }


def create_cached_rafdb_dataloader(
    split: str,
    batch_size: int = 32,
    shuffle: Optional[bool] = None,
    num_workers: int = 0,
    cache_dir: str = "data/cache/rafdb_cache",
    transform: Optional[Any] = None,
) -> Tuple[CachedRAFDBDataset, Any]:
    """
    Factory function to instantiate CachedRAFDBDataset and corresponding PyTorch DataLoader.
    """
    if shuffle is None:
        shuffle = (split == "train")

    dataset = CachedRAFDBDataset(
        split=split,
        cache_dir=cache_dir,
        transform=transform,
    )

    if _TORCH_AVAILABLE and DataLoader is not None:
        loader = DataLoader(
            dataset,
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            pin_memory=False,
        )
    else:
        loader = None

    return dataset, loader


class RAFDBDataset(Dataset):
    """
    PyTorch Dataset for RAF-DB Facial Emotion Recognition (Online Parquet Extraction).
    """

    def __init__(
        self,
        split: Optional[str] = None,
        manifest_path: Optional[str] = None,
        parquet_path: str = "data/raw/raf-db/train-00000-of-00001.parquet",
        pipeline: Optional[FacePipeline] = None,
        transform: Optional[Any] = None,
    ):
        """
        Args:
            split: Split name ('train', 'val', or 'test').
            manifest_path: Explicit path to manifest CSV. If None, resolves from split.
            parquet_path: Path to RAF-DB Parquet file.
            pipeline: Optional FacePipeline instance. If None, instantiates a default FacePipeline.
            transform: Optional additional PyTorch transform applied to image tensor.
        """
        super().__init__()
        if manifest_path is None:
            if split is None:
                raise ValueError("Either 'split' or 'manifest_path' must be provided.")
            manifest_path = os.path.join("data", "manifests", f"rafdb_{split}.csv")

        self.manifest_path = manifest_path
        self.parquet_path = parquet_path
        self.split = split
        self.transform = transform

        if not os.path.exists(self.manifest_path):
            raise FileNotFoundError(f"Manifest CSV not found: {self.manifest_path}")

        # Load manifest rows
        self.samples: List[Dict[str, Any]] = []
        with open(self.manifest_path, mode="r", newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                self.samples.append({
                    "image_path": row["image_path"],
                    "original_raf_label": int(row["original_raf_label"]),
                    "canonical_label": int(row["canonical_label"]),
                    "class_name": row["class_name"],
                    "split": row.get("split", self.split or ""),
                })

        # Load Parquet image store (shared memory cache)
        self.image_store = get_parquet_image_store(self.parquet_path)

        # Initialize or reuse FacePipeline
        if pipeline is None:
            self.pipeline = FacePipeline()
        else:
            self.pipeline = pipeline

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """
        Retrieves sample at index idx from raw Parquet store and runs FacePipeline.
        Returns:
            Dict containing:
                "image": torch.Tensor of shape (3, 224, 224), float32, ImageNet-normalized
                "label": int in range 0..6 (canonical class index)
                "geometry": torch.Tensor of shape (62,), float32
                "geometry_valid": bool
                "face_detected": bool
                "fallback_used": bool
                "image_path": str
                "class_name": str
        """
        record = self.samples[idx]
        image_path = record["image_path"]

        if image_path not in self.image_store:
            raise KeyError(f"Image {image_path} not found in Parquet store.")

        raw_bytes = self.image_store[image_path]

        # Decode JPEG bytes to BGR then convert to RGB
        buf = np.frombuffer(raw_bytes, dtype=np.uint8)
        img_bgr = cv2.imdecode(buf, cv2.IMREAD_COLOR)
        if img_bgr is None:
            raise RuntimeError(f"Failed to decode image from bytes for {image_path}")

        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

        # Execute preprocessing with is_webcam=False (dataset mode)
        result = self.pipeline.process_image(img_rgb, is_webcam=False)

        image_np = result["image_tensor"]
        if image_np is None:
            raise RuntimeError(f"Unexpected None image_tensor for {image_path} in dataset mode.")

        # Convert to PyTorch tensors if torch is available
        if _TORCH_AVAILABLE and torch is not None:
            image_tensor = torch.from_numpy(image_np).float()
            if self.transform is not None:
                image_tensor = self.transform(image_tensor)
            geom_np = result.get("geometry_vector", np.zeros(62, dtype=np.float32))
            geometry_tensor = torch.from_numpy(geom_np).float()
        else:
            image_tensor = image_np
            geometry_tensor = result.get("geometry_vector", np.zeros(62, dtype=np.float32))

        label = record["canonical_label"]

        return {
            "image": image_tensor,
            "label": label,
            "geometry": geometry_tensor,
            "geometry_valid": bool(result.get("geometry_valid", False)),
            "face_detected": bool(result.get("face_detected", False)),
            "fallback_used": bool(result.get("fallback_used", False)),
            "image_path": image_path,
            "class_name": record["class_name"],
        }


def create_rafdb_dataloader(
    split: str,
    batch_size: int = 32,
    shuffle: Optional[bool] = None,
    num_workers: int = 0,
    pipeline: Optional[FacePipeline] = None,
    manifest_path: Optional[str] = None,
    parquet_path: str = "data/raw/raf-db/train-00000-of-00001.parquet",
) -> Tuple[RAFDBDataset, Any]:
    """
    Factory function to instantiate RAFDBDataset and corresponding PyTorch DataLoader.
    """
    if shuffle is None:
        shuffle = (split == "train")

    dataset = RAFDBDataset(
        split=split,
        manifest_path=manifest_path,
        parquet_path=parquet_path,
        pipeline=pipeline,
    )

    if _TORCH_AVAILABLE and DataLoader is not None:
        loader = DataLoader(
            dataset,
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            pin_memory=False,
        )
    else:
        loader = None

    return dataset, loader
